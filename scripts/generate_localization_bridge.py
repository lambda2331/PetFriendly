"""Validate ARB parity and generate the source-copy bridge. No network needed.

Keep existing message IDs stable. Add UI copy to app_ru.arb with a description
containing its source string; add translations to every supported catalog.
"""
import json,pathlib,re
root=pathlib.Path(__file__).resolve().parents[1]
base=json.loads((root/'lib/l10n/arb/app_ru.arb').read_text())
keys={key for key in base if not key.startswith('@')}
for lang in ['en','be','pl']:
 catalog=json.loads((root/f'lib/l10n/arb/app_{lang}.arb').read_text())
 assert {key for key in catalog if not key.startswith('@')} == keys, f'{lang}: missing/extra message keys'
 for key in keys:
  assert catalog[key],f'{lang}: empty {key}'
  assert set(re.findall(r'\{(p\d+)\}',catalog[key])) == set(re.findall(r'\{(p\d+)\}',base[key])),f'{lang}: placeholders {key}'
lines=["// Generated by scripts/generate_localization_bridge.py from the Russian ARB.","import 'generated/app_localizations.dart';","String translateMessage(AppLocalizations l, String source, Map<String, Object?> arguments) => switch (source) {"]
for key in sorted(keys):
 if not key.startswith('message'):continue
 source=base['@'+key]['description'];args=list(base['@'+key].get('placeholders',{}))
 call='l.'+key+('('+', '.join("(arguments['"+a+"'] ?? '').toString()" for a in args)+')' if args else '')
 lines.append('  '+json.dumps(source,ensure_ascii=False).replace('$','\\$')+' => '+call+',')
lines+=['  _ => source,','};'];(root/'lib/l10n/message_bridge.dart').write_text('\n'.join(lines)+'\n')
print(f'Validated {len(keys)} messages in four languages')
